#ifndef LOADCELL_H
#define LOADCELL_H

#include <Arduino.h>

#include "Eris.h"
#include <eriscommon.h>
#include <eris_sensor.h>   // ERIS_SENSOR_EX

/*
 * Loadcell: the HX711 and the FSR divider, read together.
 *
 * The sampling thread is the ONLY code that touches the HX711. Tare and
 * calibration are requests that the thread carries out on its own fresh
 * conversions, so a TARE typed while streaming never races a read in
 * progress (the same single-owner rule Eris uses for I2C buses).
 *
 * Force = (raw - offset) / countsPerN.
 */
namespace Loadcell{

void begin(void);        // HX711 + ADC setup, auto-tare request, then FSRCal::start()

// Requests, served by the sampling thread over LOADCELL_AVG_SAMPLES fresh
// conversions. They return false if another request is still running.
bool requestTare(void);
bool requestCalibration(float knownNewtons);   // the force on the cell NOW
bool busy(void);

void  setScale(float countsPerN);   // LSCALE: paste a value LCAL printed earlier
float scale(void);
long  offset(void);
bool  calibrated(void);
bool  present(void);

void printStatus(void);   // LC command

}

/*
 * The calibration stream, generated by ERIS_SENSOR_EX in loadcell.cpp:
 * FSRCal::buffer and FSRCal::start(). One sample per HX711 conversion, with the
 * FSR read on the same tick.
 */
namespace FSRCal{
extern ErisBuffer<FSRCalSample_t> buffer;
void start(void);
}

#endif
